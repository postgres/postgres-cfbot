--
-- int16_overflow.sql
--
-- Regression tests for the int16 (128-bit signed integer) extension focusing
-- on values that exceed the int64 range, overflow detection, boundary
-- conditions, and sign combinations.  These tests are designed to verify
-- correctness of both the native __int128 and the struct-based INT128
-- fallback code paths.
--
-- This file assumes the extension is already loaded (by the preceding
-- int16.sql test).
--

--
-- Constants for readability
--
-- INT64_MAX  = 9223372036854775807
-- INT64_MIN  = -9223372036854775808
-- 2^63       = 9223372036854775808
-- 2^63+1     = 9223372036854775809
-- 2^64       = 18446744073709551616
-- 2^126      = 85070591730234615865843651857942052864
-- INT16_MAX  = 170141183460469231731687303715884105727
-- INT16_MIN  = -170141183460469231731687303715884105728

-- =========================================================================
-- Addition
-- =========================================================================
SELECT '9223372036854775808'::int16 + '9223372036854775808'::int16;  -- 2^63 + 2^63 = 2^64
SELECT '-9223372036854775809'::int16 + '-9223372036854775809'::int16; -- -(2^63+1) + -(2^63+1)
SELECT '170141183460469231731687303715884105727'::int16 + '-170141183460469231731687303715884105728'::int16; -- MAX + MIN
SELECT '170141183460469231731687303715884105727'::int16 + '1'::int16; -- overflow
SELECT '-170141183460469231731687303715884105728'::int16 + '-1'::int16; -- overflow
SELECT '18446744073709551616'::int16 + '0'::int16; -- 2^64 + 0
SELECT '-18446744073709551616'::int16 + '18446744073709551616'::int16; -- -2^64 + 2^64
SELECT '9223372036854775807'::int16 + '9223372036854775808'::int16; -- INT64_MAX + 2^63
SELECT '-9223372036854775808'::int16 + '-9223372036854775808'::int16; -- INT64_MIN + INT64_MIN
SELECT '85070591730234615865843651857942052864'::int16 + '85070591730234615865843651857942052864'::int16; -- 2^126 + 2^126 (overflow)

-- =========================================================================
-- Subtraction
-- =========================================================================
SELECT '-9223372036854775809'::int16 - '9223372036854775808'::int16; -- -(2^63+1) - 2^63
SELECT '9223372036854775808'::int16 - '-9223372036854775809'::int16; -- 2^63 - -(2^63+1)
SELECT '170141183460469231731687303715884105727'::int16 - '-1'::int16; -- MAX - (-1) = overflow
SELECT '-170141183460469231731687303715884105728'::int16 - '1'::int16; -- MIN - 1 = overflow
SELECT '18446744073709551616'::int16 - '1'::int16; -- 2^64 - 1
SELECT '0'::int16 - '-18446744073709551616'::int16; -- 0 - (-2^64)
SELECT '170141183460469231731687303715884105727'::int16 - '170141183460469231731687303715884105726'::int16; -- MAX - (MAX-1)
SELECT '-170141183460469231731687303715884105727'::int16 - '-170141183460469231731687303715884105728'::int16; -- -(MIN+1) - MIN
SELECT '9223372036854775808'::int16 - '9223372036854775807'::int16; -- 2^63 - INT64_MAX
SELECT '-9223372036854775809'::int16 - '-9223372036854775808'::int16; -- -(2^63+1) - INT64_MIN

-- =========================================================================
-- Multiplication
-- =========================================================================
SELECT '3000000000'::int16 * '3000000000'::int16;  -- 9e18 > INT64_MAX
SELECT '-3000000000'::int16 * '3000000000'::int16; -- -9e18
SELECT '3000000000'::int16 * '-3000000000'::int16; -- -9e18
SELECT '-3000000000'::int16 * '-3000000000'::int16; -- 9e18
SELECT '170141183460469231731687303715884105727'::int16 * '2'::int16; -- overflow
SELECT '18446744073709551616'::int16 * '18446744073709551616'::int16; -- 2^64 * 2^64 overflow
SELECT '4294967296'::int16 * '4294967296'::int16;  -- 2^32 * 2^32 = 2^64
SELECT '-4294967296'::int16 * '4294967296'::int16; -- -2^64
SELECT '9223372036854775807'::int16 * '9223372036854775807'::int16; -- INT64_MAX^2
SELECT '0'::int16 * '18446744073709551616'::int16; -- 0 * 2^64
SELECT '18446744073709551616'::int16 * '1'::int16; -- 2^64 * 1
SELECT '18446744073709551615'::int16 * '2'::int16; -- (2^64-1) * 2

-- =========================================================================
-- Division
-- =========================================================================
SELECT '170141183460469231731687303715884105727'::int16 / '170141183460469231731687303715884105727'::int16; -- MAX / MAX = 1
SELECT '170141183460469231731687303715884105727'::int16 / '-1'::int16; -- MAX / -1 = -MAX
SELECT '-170141183460469231731687303715884105728'::int16 / '-1'::int16; -- MIN / -1 = overflow
SELECT '170141183460469231731687303715884105727'::int16 / '2'::int16; -- MAX / 2
SELECT '-170141183460469231731687303715884105728'::int16 / '2'::int16; -- MIN / 2
SELECT '18446744073709551616'::int16 / '9223372036854775808'::int16; -- 2^64 / 2^63 = 2
SELECT '-18446744073709551616'::int16 / '9223372036854775808'::int16; -- -2^64 / 2^63 = -2
SELECT '18446744073709551616'::int16 / '-9223372036854775808'::int16; -- 2^64 / -2^63 = -2
SELECT '-18446744073709551616'::int16 / '-9223372036854775808'::int16; -- -2^64 / -2^63 = 2
SELECT '170141183460469231731687303715884105727'::int16 / '9223372036854775807'::int16; -- MAX / INT64_MAX
SELECT '1'::int16 / '0'::int16;  -- division by zero

-- =========================================================================
-- Remainder (modulo)
-- =========================================================================
SELECT '170141183460469231731687303715884105727'::int16 % '10'::int16;  -- MAX % 10
SELECT '-170141183460469231731687303715884105728'::int16 % '10'::int16; -- MIN % 10
SELECT '170141183460469231731687303715884105727'::int16 % '-10'::int16;  -- MAX % -10
SELECT '-170141183460469231731687303715884105728'::int16 % '-10'::int16; -- MIN % -10
SELECT '18446744073709551616'::int16 % '9223372036854775808'::int16; -- 2^64 % 2^63 = 0
SELECT '18446744073709551617'::int16 % '9223372036854775808'::int16; -- (2^64+1) % 2^63 = 1
SELECT '-18446744073709551617'::int16 % '9223372036854775808'::int16; -- -(2^64+1) % 2^63 = -1
SELECT '18446744073709551617'::int16 % '-9223372036854775808'::int16; -- (2^64+1) % -2^63 = 1
SELECT '-18446744073709551617'::int16 % '-9223372036854775808'::int16; -- -(2^64+1) % -2^63 = -1
SELECT '1'::int16 % '0'::int16;  -- division by zero

-- =========================================================================
-- Unary minus
-- =========================================================================
SELECT -'170141183460469231731687303715884105727'::int16;  -- -MAX
SELECT -'-170141183460469231731687303715884105728'::int16; -- -MIN = overflow
SELECT -'9223372036854775808'::int16;  -- -2^63
SELECT -'-9223372036854775808'::int16; -- 2^63
SELECT -'18446744073709551616'::int16; -- -2^64

-- =========================================================================
-- Bitwise AND
-- =========================================================================
SELECT '18446744073709551616'::int16 & '18446744073709551616'::int16; -- 2^64 & 2^64
SELECT '18446744073709551616'::int16 & '1'::int16; -- 2^64 & 1 = 0
SELECT '18446744073709551617'::int16 & '1'::int16; -- 2^64+1 & 1 = 1
SELECT '-1'::int16 & '18446744073709551616'::int16; -- -1 & 2^64 = 2^64
SELECT '-1'::int16 & '0'::int16; -- -1 & 0 = 0
SELECT '170141183460469231731687303715884105727'::int16 & '0'::int16; -- MAX & 0
SELECT '-170141183460469231731687303715884105728'::int16 & '0'::int16; -- MIN & 0

-- =========================================================================
-- Bitwise OR
-- =========================================================================
SELECT '18446744073709551616'::int16 | '1'::int16; -- 2^64 | 1 = 2^64+1
SELECT '18446744073709551616'::int16 | '0'::int16; -- 2^64 | 0 = 2^64
SELECT '0'::int16 | '18446744073709551616'::int16; -- 0 | 2^64 = 2^64
SELECT '-1'::int16 | '0'::int16; -- -1 | 0 = -1
SELECT '18446744073709551615'::int16 | '1'::int16; -- (2^64-1) | 1 = 2^64-1

-- =========================================================================
-- Bitwise XOR
-- =========================================================================
SELECT '18446744073709551616'::int16 # '1'::int16; -- 2^64 # 1 = 2^64+1
SELECT '18446744073709551616'::int16 # '18446744073709551616'::int16; -- 2^64 # 2^64 = 0
SELECT '0'::int16 # '18446744073709551616'::int16; -- 0 # 2^64 = 2^64
SELECT '-1'::int16 # '0'::int16; -- -1 # 0 = -1
SELECT '-1'::int16 # '18446744073709551616'::int16; -- -1 # 2^64 = -(2^64+1)
SELECT '-1'::int16 # '-1'::int16; -- -1 # -1 = 0

-- =========================================================================
-- Bitwise NOT
-- =========================================================================
SELECT ~'0'::int16; -- ~0 = -1
SELECT ~'-1'::int16; -- ~(-1) = 0
SELECT ~'18446744073709551616'::int16; -- ~(2^64)
SELECT ~'170141183460469231731687303715884105727'::int16; -- ~MAX = MIN
SELECT ~'-170141183460469231731687303715884105728'::int16; -- ~MIN = MAX

-- =========================================================================
-- Left shift (shifts 0-127 only; behavior matches int8: raw C shift)
-- =========================================================================
SELECT '1'::int16 << 0;   -- 1
SELECT '1'::int16 << 1;   -- 2
SELECT '1'::int16 << 64;  -- 2^64
SELECT '1'::int16 << 127; -- 2^127 = INT16_MIN
SELECT '18446744073709551616'::int16 << 1;  -- 2^64 << 1 = 2^65
SELECT '18446744073709551616'::int16 << 63; -- 2^64 << 63 = 2^127 = INT16_MIN
SELECT '-1'::int16 << 1;  -- -1 << 1 = -2
SELECT '-1'::int16 << 0;  -- -1 << 0 = -1

-- =========================================================================
-- Right shift (shifts 0-127 only; arithmetic shift for negative values)
-- =========================================================================
SELECT '-1'::int16 >> 1;  -- -1 >> 1 = -1 (arithmetic)
SELECT '-1'::int16 >> 64; -- -1 >> 64 = -1 (arithmetic)
SELECT '18446744073709551616'::int16 >> 1;  -- 2^64 >> 1 = 2^63
SELECT '18446744073709551616'::int16 >> 64; -- 2^64 >> 64 = 1
SELECT '18446744073709551616'::int16 >> 0;  -- 2^64 >> 0 = 2^64
SELECT '170141183460469231731687303715884105727'::int16 >> 1; -- MAX >> 1
SELECT '-170141183460469231731687303715884105728'::int16 >> 1; -- MIN >> 1
SELECT '-170141183460469231731687303715884105728'::int16 >> 64; -- MIN >> 64
SELECT '0'::int16 >> 10; -- 0 >> 10 = 0

