-- =========================================================================
-- Aggregates with values exceeding int64 range
-- =========================================================================
CREATE TABLE int16_overflow_test (x int16);
INSERT INTO int16_overflow_test VALUES ('9223372036854775808'), ('9223372036854775808'); -- two 2^63 values

-- sum = 2^64 (exceeds int64, fits in int16)
SELECT sum(x) FROM int16_overflow_test;

-- avg = 2^63 (returns numeric)
SELECT avg(x) FROM int16_overflow_test;

-- min/max
SELECT min(x), max(x) FROM int16_overflow_test;

-- Sum overflow: add MAX then add 2^63
INSERT INTO int16_overflow_test VALUES ('170141183460469231731687303715884105727');
SELECT sum(x) FROM int16_overflow_test; -- overflow

-- Clean up the overflow row
DELETE FROM int16_overflow_test WHERE x = '170141183460469231731687303715884105727'::int16;

-- avg with 3 values all = 2^64
DELETE FROM int16_overflow_test;
INSERT INTO int16_overflow_test VALUES ('18446744073709551616'), ('18446744073709551616'), ('18446744073709551616');
SELECT sum(x) FROM int16_overflow_test; -- 3 * 2^64
SELECT avg(x) FROM int16_overflow_test; -- 2^64 as numeric

DROP TABLE int16_overflow_test;

-- =========================================================================
-- int16_avg_state type (internal aggregate state for avg)
-- =========================================================================
-- The state type is internal-only (cannot accept direct input), so we
-- verify it works correctly through the avg() aggregate with large values
-- that exercise the INT128 sum accumulator.
CREATE TABLE int16_avg_state_test (x int16);
INSERT INTO int16_avg_state_test VALUES
    ('9223372036854775808'),   -- 2^63
    ('9223372036854775808'),   -- 2^63
    ('9223372036854775808'),   -- 2^63
    ('9223372036854775808'),   -- 2^63
    (NULL);                     -- should be skipped
-- avg = 2^63 (sum = 4 * 2^63 = 2^65, count = 4, avg = 2^63)
SELECT avg(x) FROM int16_avg_state_test;

-- Larger values: sum exceeds int64 range significantly
DELETE FROM int16_avg_state_test;
INSERT INTO int16_avg_state_test VALUES
    ('18446744073709551616'),   -- 2^64
    ('18446744073709551616'),   -- 2^64
    ('18446744073709551616');   -- 2^64
-- avg = 2^64
SELECT avg(x) FROM int16_avg_state_test;

DROP TABLE int16_avg_state_test;
