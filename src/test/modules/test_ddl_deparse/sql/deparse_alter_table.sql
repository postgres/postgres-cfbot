--
-- Corner cases for DDL deparsing of ALTER TABLE.
--
-- See deparse_create_table.sql.  As there, the cases here are those where a
-- wrong result would still leave the same catalog state, plus the
-- subcommands the core tests don't have.
--
-- The event triggers created by the test_ddl_deparse script, first in the
-- schedule, are still installed.  Their "DDL test:" NOTICEs appear below.
--
LOAD 'test_ddl_deparse';
SET test_ddl_deparse.execute_deparsed_ddl = on;
SET test_ddl_deparse.print_deparsed_ddl = text;

CREATE SCHEMA deparse_at;

-- Several subcommands the user wrote stay in one ALTER TABLE, which preserves
-- the single table rewrite of the original.
CREATE TABLE deparse_at.t (a int, b text, c int);
ALTER TABLE deparse_at.t ADD COLUMN d int, ALTER COLUMN b SET NOT NULL, DROP COLUMN c;

-- A constraint the user didn't name is emitted without a name.  This covers
-- a constraint written with a column definition too, which parse analysis
-- splits out into a subcommand of its own.
CREATE TABLE deparse_at.con (a int, b int);
CREATE TABLE deparse_at.ref (x int PRIMARY KEY);
ALTER TABLE deparse_at.con ADD CHECK (b > 0) NOT VALID;
ALTER TABLE deparse_at.con ADD FOREIGN KEY (a) REFERENCES deparse_at.ref (x)
	ON DELETE CASCADE;
ALTER TABLE deparse_at.con ADD COLUMN d int CHECK (d > 0);
ALTER TABLE deparse_at.con ADD COLUMN e int CONSTRAINT named_e CHECK (e > 0);
SELECT conname, pg_get_constraintdef(oid)
  FROM pg_constraint
  WHERE conrelid = 'deparse_at.con'::regclass
  ORDER BY conname COLLATE "C";

-- ADD NOT NULL for a column that already has one merges with the existing
-- constraint and creates no catalog row, so there is nothing to recover under
-- a name the user did not give.  The subcommand must still be emitted, not
-- dropped, which would leave the statement with no subcommand at all.  The
-- core tests have no such statement.
CREATE TABLE deparse_at.nnm (a int NOT NULL);
ALTER TABLE deparse_at.nnm ADD NOT NULL a;
CREATE TABLE deparse_at.nnmp (a int NOT NULL);
CREATE TABLE deparse_at.nnmc () INHERITS (deparse_at.nnmp);
ALTER TABLE deparse_at.nnmc ADD NOT NULL a;

-- An ALTER COLUMN TYPE whose USING references a column that a sibling
-- subcommand drops.  The USING is rendered to text at prep time, before the
-- drop, so it can still name the column.  Both statement orders behave
-- identically, as execution reorders subcommands by pass.  The core tests
-- never combine the two.
CREATE TABLE deparse_at.u (a int, b int);
INSERT INTO deparse_at.u VALUES (1, 42);
ALTER TABLE deparse_at.u ALTER COLUMN a TYPE text USING b::text, DROP COLUMN b;
CREATE TABLE deparse_at.u2 (a int, b int);
INSERT INTO deparse_at.u2 VALUES (1, 42);
ALTER TABLE deparse_at.u2 DROP COLUMN b, ALTER COLUMN a TYPE text USING b::text;

-- Identity clauses repeated on one column are each emitted as written, not
-- as the first of them
CREATE TABLE deparse_at.id_repeat (a int GENERATED BY DEFAULT AS IDENTITY);
ALTER TABLE deparse_at.id_repeat
  ALTER COLUMN a SET GENERATED ALWAYS,
  ALTER COLUMN a SET GENERATED BY DEFAULT;
SELECT attidentity FROM pg_attribute
  WHERE attrelid = 'deparse_at.id_repeat'::regclass AND attname = 'a';
ALTER TABLE deparse_at.id_repeat
  ALTER COLUMN a SET INCREMENT BY 3,
  ALTER COLUMN a SET INCREMENT BY 7;
SELECT seqincrement FROM pg_sequence
  WHERE seqrelid = 'deparse_at.id_repeat_a_seq'::regclass;

-- Each default comes from its own subcommand, not from the catalog after the
-- whole command.  Existing rows get the ADD COLUMN default, and later
-- inserts the SET DEFAULT one.
CREATE TABLE deparse_at.defaults (a int);
INSERT INTO deparse_at.defaults VALUES (1);
ALTER TABLE deparse_at.defaults
  ADD COLUMN b int DEFAULT 1,
  ALTER COLUMN b SET DEFAULT 2;
INSERT INTO deparse_at.defaults (a) VALUES (2);
SELECT * FROM deparse_at.defaults ORDER BY a;
ALTER TABLE deparse_at.defaults
  ALTER COLUMN b SET DEFAULT 3,
  ALTER COLUMN b SET DEFAULT 4;
ALTER TABLE deparse_at.defaults
  ALTER COLUMN b SET DEFAULT NULL,
  ALTER COLUMN b SET DEFAULT 5;
ALTER TABLE deparse_at.defaults
  ADD COLUMN c int DEFAULT 10,
  ALTER COLUMN c SET DEFAULT NULL;
SELECT * FROM deparse_at.defaults ORDER BY a;
CREATE DOMAIN deparse_at.dom42 AS int DEFAULT 42;
ALTER TABLE deparse_at.defaults
  ADD COLUMN d deparse_at.dom42 DEFAULT NULL,
  ALTER COLUMN d SET DEFAULT 3;
SELECT a, d FROM deparse_at.defaults ORDER BY a;
-- likewise for a generation expression
ALTER TABLE deparse_at.defaults
  ADD COLUMN g int GENERATED ALWAYS AS (a * 2) STORED,
  ALTER COLUMN g SET EXPRESSION AS (a * 3);
SELECT a, g FROM deparse_at.defaults ORDER BY a;
ALTER TABLE deparse_at.defaults
  ALTER COLUMN g SET EXPRESSION AS (a * 4),
  ALTER COLUMN g SET EXPRESSION AS (a * 5);
-- A subcommand whose IF [NOT] EXISTS found nothing to do is not emitted, as
-- it did nothing.  The existing column must not be read in its place.
ALTER TABLE deparse_at.defaults
  ADD COLUMN IF NOT EXISTS b int DEFAULT 99,
  ALTER COLUMN b SET DEFAULT 6;
ALTER TABLE deparse_at.defaults
  ADD COLUMN IF NOT EXISTS b int GENERATED ALWAYS AS (a + 1) STORED,
  ADD COLUMN IF NOT EXISTS c text COLLATE "C",
  DROP COLUMN IF EXISTS nonesuch,
  ADD COLUMN e int;
-- nothing at all to do
ALTER TABLE deparse_at.defaults
  ADD COLUMN IF NOT EXISTS b int,
  DROP COLUMN IF EXISTS nonesuch;

-- SET STATISTICS by column number, for an unnamed expression column of an
-- index reached via ALTER TABLE naming that index.  The subcommand carries
-- the column position instead of a name.  The core tests reach such a column
-- only through ALTER INDEX, which is not deparsed.
CREATE TABLE deparse_at.ei (a int, b int);
CREATE INDEX deparse_at_ei ON deparse_at.ei ((a + b));
ALTER TABLE deparse_at.deparse_at_ei ALTER COLUMN 1 SET STATISTICS 1000;
ALTER TABLE deparse_at.deparse_at_ei ALTER COLUMN 1 SET STATISTICS DEFAULT;

-- ADD ... PRIMARY KEY USING INDEX with the deferrability clauses, which the
-- core tests never give.
CREATE TABLE deparse_at.ui3 (a int);
CREATE UNIQUE INDEX ui3_uq ON deparse_at.ui3 (a);
ALTER TABLE deparse_at.ui3
  ADD CONSTRAINT ui3_pk PRIMARY KEY USING INDEX ui3_uq DEFERRABLE INITIALLY DEFERRED;

-- CLUSTER ON a leaf partition's index.  That index has a pg_inherits row, so
-- the inheritance-child skip must not take it for a recursed child.
CREATE TABLE deparse_at.cl (a int NOT NULL) PARTITION BY RANGE (a);
CREATE TABLE deparse_at.cl1 PARTITION OF deparse_at.cl FOR VALUES FROM (0) TO (10);
CREATE INDEX cl_a_idx ON deparse_at.cl (a);
ALTER TABLE deparse_at.cl1 CLUSTER ON cl1_a_idx;

-- The ENABLE spellings of the trigger and rule subcommands.  The core tests
-- use none of these four.
CREATE TABLE deparse_at.tr (a int);
CREATE FUNCTION deparse_at.trigfn() RETURNS trigger LANGUAGE plpgsql
	AS 'BEGIN RETURN NEW; END';
CREATE TRIGGER trg BEFORE INSERT ON deparse_at.tr
	FOR EACH ROW EXECUTE FUNCTION deparse_at.trigfn();
CREATE RULE trg_rule AS ON INSERT TO deparse_at.tr DO INSTEAD NOTHING;
ALTER TABLE deparse_at.tr ENABLE REPLICA TRIGGER trg;
ALTER TABLE deparse_at.tr DISABLE TRIGGER ALL;
ALTER TABLE deparse_at.tr ENABLE TRIGGER ALL;
ALTER TABLE deparse_at.tr ENABLE TRIGGER USER;
ALTER TABLE deparse_at.tr ENABLE ALWAYS RULE trg_rule;

-- IF EXISTS on the table is kept in every form that accepts it.
CREATE TABLE deparse_at.guarded (a int CONSTRAINT guarded_check CHECK (a > 0));
ALTER TABLE IF EXISTS ONLY deparse_at.guarded ADD COLUMN b int;
ALTER TABLE IF EXISTS ONLY deparse_at.guarded RENAME COLUMN b TO c;
ALTER TABLE IF EXISTS ONLY deparse_at.guarded
  RENAME CONSTRAINT guarded_check TO renamed_check;
ALTER TABLE IF EXISTS deparse_at.guarded RENAME TO guarded2;
CREATE SCHEMA deparse_guard;
ALTER TABLE IF EXISTS deparse_at.guarded2 SET SCHEMA deparse_guard;
DROP TABLE deparse_guard.guarded2;
DROP SCHEMA deparse_guard;

-- IF EXISTS on a missing table is a no-op: nothing is collected, so there is
-- nothing to deparse and no warning.
ALTER TABLE IF EXISTS deparse_at.nonesuch ADD COLUMN z int;
ALTER TABLE IF EXISTS deparse_at.nonesuch RENAME COLUMN a TO b;
ALTER TABLE IF EXISTS deparse_at.nonesuch RENAME CONSTRAINT c TO d;
ALTER TABLE IF EXISTS deparse_at.nonesuch RENAME TO other;
ALTER TABLE IF EXISTS deparse_at.nonesuch SET SCHEMA public;

-- SET STORAGE and SET COMPRESSION values are quoted as identifiers
CREATE TABLE deparse_at.st (a text);
ALTER TABLE deparse_at.st ALTER COLUMN a SET STORAGE "Main",
  ALTER COLUMN a SET COMPRESSION "default";

-- DDL that user code runs while the statement executes, here from a USING
-- expression, is not taken for the statement itself
CREATE TABLE deparse_at.ut (a int);
INSERT INTO deparse_at.ut VALUES (1);
CREATE TABLE deparse_at.uo (b int);
CREATE FUNCTION deparse_at.alter_other(int) RETURNS bigint LANGUAGE plpgsql AS
$$ BEGIN ALTER TABLE deparse_at.uo ADD COLUMN IF NOT EXISTS c int; RETURN $1; END $$;
ALTER TABLE deparse_at.ut ALTER COLUMN a TYPE bigint USING deparse_at.alter_other(a);

-- A table dropped by a ddl_command_end trigger that fires before ours (event
-- triggers fire in name order) can't be deparsed
CREATE SCHEMA deparse_at2;
CREATE TABLE deparse_at.gone (a int);
CREATE TABLE deparse_at.gone3 (a int);
CREATE FUNCTION deparse_at.drop_moved() RETURNS event_trigger LANGUAGE plpgsql AS
$$ BEGIN
  IF tg_tag = 'ALTER TABLE' THEN
    DROP TABLE IF EXISTS deparse_at.gone2, deparse_at2.gone3;
  END IF;
END $$;
CREATE EVENT TRIGGER a_drop_moved ON ddl_command_end
  EXECUTE FUNCTION deparse_at.drop_moved();
\set VERBOSITY sqlstate
ALTER TABLE deparse_at.gone RENAME TO gone2;
ALTER TABLE deparse_at.gone3 SET SCHEMA deparse_at2;
\set VERBOSITY default
DROP EVENT TRIGGER a_drop_moved;

-- Each NOT NULL the user wrote is emitted once, also where ADD COLUMN or ADD
-- PRIMARY KEY generates another NOT NULL on the same column
CREATE TABLE deparse_at.nn (a int, b int);
ALTER TABLE deparse_at.nn ADD COLUMN c int NOT NULL DEFAULT 0, ADD NOT NULL c;
ALTER TABLE deparse_at.nn ADD CONSTRAINT b_nn NOT NULL b, ADD NOT NULL b;
ALTER TABLE deparse_at.nn ADD PRIMARY KEY (a), ADD NOT NULL a;

-- The CLUSTER ON and REPLICA IDENTITY that ALTER COLUMN TYPE re-applies to a
-- rebuilt index are not emitted, also when the user writes one of their own
CREATE TABLE deparse_at.ri (a int NOT NULL, b int);
CREATE UNIQUE INDEX ri_a ON deparse_at.ri (a);
CREATE INDEX ri_b ON deparse_at.ri (b);
ALTER TABLE deparse_at.ri CLUSTER ON ri_a, REPLICA IDENTITY USING INDEX ri_a;
ALTER TABLE deparse_at.ri ALTER COLUMN a TYPE bigint, CLUSTER ON ri_b,
  REPLICA IDENTITY FULL;
ALTER TABLE deparse_at.ri SET WITHOUT CLUSTER;

-- Column OPTIONS on a foreign table are not supported, so the command runs
-- as written
CREATE FOREIGN DATA WRAPPER deparse_at_fdw;
CREATE SERVER deparse_at_srv FOREIGN DATA WRAPPER deparse_at_fdw;
CREATE FOREIGN TABLE deparse_at.ft (a int) SERVER deparse_at_srv;
ALTER TABLE deparse_at.ft ADD COLUMN b int OPTIONS (x 'y');
SELECT attname, attfdwoptions FROM pg_attribute
  WHERE attrelid = 'deparse_at.ft'::regclass AND attnum > 0
  ORDER BY attnum;

RESET test_ddl_deparse.print_deparsed_ddl;
RESET test_ddl_deparse.execute_deparsed_ddl;

DROP SCHEMA deparse_at CASCADE;
DROP SCHEMA deparse_at2;
DROP SERVER deparse_at_srv;
DROP FOREIGN DATA WRAPPER deparse_at_fdw;
