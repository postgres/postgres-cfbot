--
-- Corner cases for DDL deparsing of CREATE TABLE.
--
-- test_ddl_deparse intercepts each supported command, runs the original in a
-- subtransaction that is rolled back, deparses the collected command, and
-- executes the reconstruction for real.  The deparsed text is reported as a
-- NOTICE, so the expected output pins it.
--
-- Ordinary syntax is covered by 001_deparse_regress.pl, which replays the
-- core regression tests.  The cases here are those where a wrong result would
-- still leave the same catalog state, so the replay can't catch it, plus a
-- few the core tests don't have.
--
-- The event triggers created by the test_ddl_deparse script, which runs
-- first in this schedule, are still installed.  Their "DDL test:" NOTICEs
-- appear below too.
--
LOAD 'test_ddl_deparse';
SET test_ddl_deparse.execute_deparsed_ddl = on;
SET test_ddl_deparse.print_deparsed_ddl = text;

CREATE SCHEMA deparse_tests;

-- A serial column is emitted as the user wrote it.
CREATE TABLE deparse_tests.t_serial (
a serial,
b serial4,
c bigserial,
d smallserial
);

-- COMPRESSION and STORAGE are emitted only where the user wrote them.
CREATE TABLE deparse_tests.t_options (
a text COMPRESSION pglz,
b text COMPRESSION default,
c text STORAGE external,
d text STORAGE "Main",
e text
);
SELECT attname, attcompression, attstorage
  FROM pg_attribute
  WHERE attrelid = 'deparse_tests.t_options'::regclass AND attnum > 0
  ORDER BY attnum;

-- A constraint the user didn't name is emitted without a name.  Inline
-- constraints are emitted as table constraints.
CREATE TABLE deparse_tests.t_constr (
a int PRIMARY KEY,
b int REFERENCES deparse_tests.t_constr (a) NOT NULL,
c text DEFAULT 'x' CHECK (c <> ''),
CONSTRAINT named_check CHECK (a > 0)
);
SELECT conname, contype, pg_get_constraintdef(oid)
  FROM pg_constraint
  WHERE conrelid = 'deparse_tests.t_constr'::regclass
  ORDER BY conname COLLATE "C";

-- DEFAULT NULL is not stored in pg_attrdef, but is still emitted.
CREATE TABLE deparse_tests.t_defnull (a int DEFAULT NULL, b text DEFAULT NULL::text);

-- The temp schema is emitted as pg_temp rather than as this backend's own
-- pg_temp_<n>, which would resolve to the same schema on replay.
CREATE TEMP TABLE t_temp (a int);
DROP TABLE t_temp;

-- Identity sequence options that parse analysis consumes are still in the raw
-- tree.  SEQUENCE NAME has to be emitted; OWNED BY is dropped, since
-- execution overrides it.  The core tests use neither.
CREATE TABLE deparse_tests.t_seqname (
id int GENERATED ALWAYS AS IDENTITY
	(SEQUENCE NAME deparse_tests.t_seqname_seq START WITH 5)
);
SELECT relname FROM pg_class WHERE oid = 'deparse_tests.t_seqname_seq'::regclass;
CREATE TABLE deparse_tests.t_ownedby (
id int GENERATED BY DEFAULT AS IDENTITY (OWNED BY NONE)
);

-- Types whose typmod is written inside the type name.  The core tests have
-- no interval column with a field list.
CREATE TABLE deparse_tests.t_types (
a interval hour to minute,
b timestamp(3) with time zone
);

-- The columns a LIKE clause contributes are read back from the catalog.
CREATE TABLE deparse_tests.t_like_src (
a int NOT NULL,
b text COLLATE "C",
c numeric(10,2) STORAGE plain,
d int DEFAULT 7,
e int GENERATED ALWAYS AS (d * 2) STORED
);
CREATE TABLE deparse_tests.t_like (LIKE deparse_tests.t_like_src);

-- written-out and LIKE columns interleave in catalog order
CREATE TABLE deparse_tests.t_like_mixed (
x serial,
LIKE deparse_tests.t_like_src,
y int DEFAULT 1
);

-- the options that land in the table definition are all recovered
CREATE TABLE deparse_tests.t_like_incl (
LIKE deparse_tests.t_like_src
	INCLUDING DEFAULTS INCLUDING GENERATED INCLUDING CONSTRAINTS
	INCLUDING STORAGE INCLUDING COMPRESSION
);

-- a NOT NULL that a LIKE column gets only from the parent it merged with
-- stays inherited
CREATE TABLE deparse_tests.t_like_par (a int CONSTRAINT par_a_nn NOT NULL);
CREATE TABLE deparse_tests.t_like_nn (a int, z text);
CREATE TABLE deparse_tests.t_like_inh (LIKE deparse_tests.t_like_nn)
  INHERITS (deparse_tests.t_like_par);
SELECT conname, conislocal, coninhcount FROM pg_constraint
  WHERE conrelid = 'deparse_tests.t_like_inh'::regclass;

-- identity comes back with the sequence parameters that were copied
CREATE TABLE deparse_tests.t_like_idsrc (
a int GENERATED BY DEFAULT AS IDENTITY (START WITH 10 INCREMENT BY 5)
);
CREATE TABLE deparse_tests.t_like_ident
  (LIKE deparse_tests.t_like_idsrc INCLUDING IDENTITY);

-- LIKE options that copy a separate object are declined
CREATE INDEX ON deparse_tests.t_like_src (a);
CREATE TABLE deparse_tests.t_like_idx
  (LIKE deparse_tests.t_like_src INCLUDING INDEXES);
CREATE TABLE deparse_tests.t_like_all
  (LIKE deparse_tests.t_like_src INCLUDING ALL);

-- USING INDEX TABLESPACE stays with the constraint it was written for, also
-- when parse analysis has merged redundant constraints.
CREATE TABLE deparse_tests.t_idxtblspc (
a int,
b int,
c int,
UNIQUE (a),
UNIQUE (b) USING INDEX TABLESPACE pg_default,
PRIMARY KEY (c)
);
CREATE TABLE deparse_tests.t_dedup (
a int,
b int,
UNIQUE (a),
UNIQUE (a),
UNIQUE (b) USING INDEX TABLESPACE pg_default,
PRIMARY KEY (a)
);

-- Index storage parameters of an index-backed constraint, which
-- pg_get_constraintdef omits for PRIMARY KEY and UNIQUE but already includes
-- for EXCLUDE.  No constraint in the core tests carries them.
CREATE TABLE deparse_tests.t_idxopts (
a int,
b int,
UNIQUE (a) WITH (fillfactor = 90),
PRIMARY KEY (b) WITH (fillfactor = 80, deduplicate_items = off)
	USING INDEX TABLESPACE pg_default DEFERRABLE
);
SELECT c.relname, c.reloptions
  FROM pg_class c
  WHERE c.relname IN ('t_idxopts_a_key', 't_idxopts_pkey')
  ORDER BY 1;
CREATE TABLE deparse_tests.t_exclopts (
c circle,
EXCLUDE USING gist (c WITH &&) WITH (fillfactor = 70)
	USING INDEX TABLESPACE pg_default DEFERRABLE
);
SELECT c.relname, c.reloptions
  FROM pg_class c
  JOIN pg_constraint con ON con.conindid = c.oid
  WHERE con.conrelid = 'deparse_tests.t_exclopts'::regclass;

-- An exclusion predicate that ruleutils renders across several lines, which
-- the deparser has to split off the definition and put back.  The core tests
-- have no such predicate.
CREATE TABLE deparse_tests.t_exclcase (
c circle,
n int,
EXCLUDE USING gist (c WITH &&)
	USING INDEX TABLESPACE pg_default
	WHERE (CASE WHEN n > 0 THEN true ELSE false END)
	DEFERRABLE
);

-- Format-string metacharacters and embedded quotes must pass through the fmt
-- expansion inertly.  No name in the core tests contains them.
CREATE TABLE deparse_tests."evil %{name}I table" (
"a""b" int,
"%{col}s" text DEFAULT 'O''Reilly',
"100%" numeric
);

-- IF NOT EXISTS on an existing relation deparses to nothing
CREATE TABLE IF NOT EXISTS deparse_tests.t_serial (a int);

-- printing works whether or not the deparsed version is executed.  The
-- serial column comes back as written, although execution expands it in
-- place.
SET test_ddl_deparse.execute_deparsed_ddl = off;
CREATE TABLE deparse_tests.t_printonly (a serial);

-- DDL that user code runs while the statement executes, here from a partition
-- bound, is not taken for the statement itself
CREATE TABLE deparse_tests.t_list (a int) PARTITION BY LIST (a);
CREATE FUNCTION deparse_tests.make_side() RETURNS int LANGUAGE plpgsql AS
$$ BEGIN CREATE TABLE deparse_tests.t_side (x int); RETURN 1; END $$;
CREATE TABLE deparse_tests.t_list1 PARTITION OF deparse_tests.t_list
  FOR VALUES IN (deparse_tests.make_side());

-- the JSON blob itself can be printed, alone or along with the command
SET test_ddl_deparse.print_deparsed_ddl = json;
CREATE TABLE deparse_tests.t_json (id serial);
SET test_ddl_deparse.print_deparsed_ddl = 'both';
SET test_ddl_deparse.execute_deparsed_ddl = on;
CREATE TABLE deparse_tests.t_both (a int DEFAULT 42);

RESET test_ddl_deparse.print_deparsed_ddl;
RESET test_ddl_deparse.execute_deparsed_ddl;

DROP SCHEMA deparse_tests CASCADE;
