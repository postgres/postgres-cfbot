--
-- TPC-E Schema and Stored Procedures for pgbench
--
-- Requires contrib/pgbench extension for in-database data generation and
-- skewed distribution functions.
--

SET client_min_messages = warning;

CREATE EXTENSION IF NOT EXISTS pgbench;

DROP TABLE IF EXISTS settlement CASCADE;
DROP TABLE IF EXISTS cash_transaction CASCADE;
DROP TABLE IF EXISTS trade_request CASCADE;
DROP TABLE IF EXISTS trade_history CASCADE;
DROP TABLE IF EXISTS trade CASCADE;
DROP TABLE IF EXISTS trade_type CASCADE;
DROP TABLE IF EXISTS watch_item CASCADE;
DROP TABLE IF EXISTS watch_list CASCADE;
DROP TABLE IF EXISTS holding_summary CASCADE;
DROP TABLE IF EXISTS holding CASCADE;
DROP TABLE IF EXISTS customer_account CASCADE;
DROP TABLE IF EXISTS customer CASCADE;
DROP TABLE IF EXISTS last_trade CASCADE;
DROP TABLE IF EXISTS security CASCADE;
DROP TABLE IF EXISTS company CASCADE;
DROP TABLE IF EXISTS broker CASCADE;

CREATE TABLE broker (
    b_id         bigint PRIMARY KEY,
    b_st_id      char(4) NOT NULL,
    b_name       varchar(49) NOT NULL,
    b_num_trades integer NOT NULL,
    b_comm_total numeric(12,2) NOT NULL
);

CREATE TABLE company (
    co_id        bigint PRIMARY KEY,
    co_st_id     char(4) NOT NULL,
    co_name      varchar(60) NOT NULL,
    co_in_id     char(2) NOT NULL,
    co_sp_rate   char(4) NOT NULL,
    co_ceo       varchar(46) NOT NULL,
    co_desc      varchar(150) NOT NULL,
    co_open_date date NOT NULL
);

CREATE TABLE security (
    s_symb          char(15) PRIMARY KEY,
    s_issue         char(6) NOT NULL,
    s_st_id         char(4) NOT NULL,
    s_name          varchar(70) NOT NULL,
    s_ex_id         char(6) NOT NULL,
    s_co_id         bigint NOT NULL,
    s_num_out       bigint NOT NULL,
    s_start_date    date NOT NULL,
    s_exch_date     date NOT NULL,
    s_pe            numeric(10,2) NOT NULL,
    s_52wk_high     numeric(8,2) NOT NULL,
    s_52wk_high_date date NOT NULL,
    s_52wk_low      numeric(8,2) NOT NULL,
    s_52wk_low_date date NOT NULL,
    s_dividend      numeric(10,2) NOT NULL,
    s_yield         numeric(5,2) NOT NULL
);

CREATE TABLE last_trade (
    lt_s_symb     char(15) PRIMARY KEY,
    lt_dts        timestamp NOT NULL,
    lt_price      numeric(8,2) NOT NULL,
    lt_open_price numeric(8,2) NOT NULL,
    lt_vol        bigint NOT NULL
);

CREATE TABLE customer (
    c_id      bigint PRIMARY KEY,
    c_tax_id  varchar(20) NOT NULL,
    c_st_id   char(4) NOT NULL,
    c_l_name  varchar(25) NOT NULL,
    c_f_name  varchar(20) NOT NULL,
    c_m_name  char(1),
    c_gndr    char(1),
    c_tier    smallint NOT NULL,
    c_dob     date NOT NULL,
    c_ad_id   bigint NOT NULL,
    c_email_1 varchar(50)
);

CREATE TABLE customer_account (
    ca_id     bigint PRIMARY KEY,
    ca_b_id   bigint NOT NULL,
    ca_c_id   bigint NOT NULL,
    ca_name   varchar(50),
    ca_tax_st smallint NOT NULL,
    ca_bal    numeric(12,2) NOT NULL
);

CREATE TABLE holding (
    h_t_id   bigint PRIMARY KEY,
    h_ca_id  bigint NOT NULL,
    h_s_symb char(15) NOT NULL,
    h_dts    timestamp NOT NULL,
    h_price  numeric(8,2) NOT NULL,
    h_qty    integer NOT NULL
);

CREATE TABLE holding_summary (
    hs_ca_id  bigint NOT NULL,
    hs_s_symb char(15) NOT NULL,
    hs_qty    integer NOT NULL,
    PRIMARY KEY (hs_ca_id, hs_s_symb)
);

CREATE TABLE watch_list (
    wl_id   bigint PRIMARY KEY,
    wl_c_id bigint NOT NULL
);

CREATE TABLE watch_item (
    wi_wl_id  bigint NOT NULL,
    wi_s_symb char(15) NOT NULL,
    PRIMARY KEY (wi_wl_id, wi_s_symb)
);

CREATE TABLE trade_type (
    tt_id      char(3) PRIMARY KEY,
    tt_name    varchar(12) NOT NULL,
    tt_is_sell boolean NOT NULL,
    tt_is_mrkt boolean NOT NULL
);

CREATE TABLE trade (
    t_id          bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1000000) PRIMARY KEY,
    t_dts         timestamp NOT NULL,
    t_st_id       char(4) NOT NULL,
    t_tt_id       char(3) NOT NULL,
    t_is_cash     boolean NOT NULL,
    t_s_symb      char(15) NOT NULL,
    t_qty         integer NOT NULL,
    t_bid_price   numeric(8,2) NOT NULL,
    t_ca_id       bigint NOT NULL,
    t_exec_name   varchar(49) NOT NULL,
    t_trade_price numeric(8,2),
    t_chrg        numeric(10,2) NOT NULL,
    t_comm        numeric(10,2) NOT NULL,
    t_tax         numeric(10,2) NOT NULL,
    t_lifo        boolean NOT NULL
);

CREATE TABLE trade_history (
    th_t_id  bigint NOT NULL,
    th_dts   timestamp NOT NULL,
    th_st_id char(4) NOT NULL,
    PRIMARY KEY (th_t_id, th_st_id)
);

CREATE TABLE trade_request (
    tr_t_id      bigint PRIMARY KEY,
    tr_tt_id     char(3) NOT NULL,
    tr_s_symb    char(15) NOT NULL,
    tr_qty       integer NOT NULL,
    tr_bid_price numeric(8,2) NOT NULL,
    tr_b_id      bigint NOT NULL
);

CREATE TABLE cash_transaction (
    ct_t_id bigint PRIMARY KEY,
    ct_dts  timestamp NOT NULL,
    ct_amt  numeric(10,2) NOT NULL,
    ct_name varchar(100) NOT NULL
);

CREATE TABLE settlement (
    se_t_id          bigint PRIMARY KEY,
    se_cash_type     varchar(40) NOT NULL,
    se_cash_due_date date NOT NULL,
    se_amt           numeric(10,2) NOT NULL
);

--
-- TPC-E: Trade-Order Transaction
--
CREATE OR REPLACE PROCEDURE pgbench_e_trade_order(
    p_ca_id        bigint,
    p_s_symb       text,
    p_tt_id        text,
    p_qty          integer,
    p_is_lifo      boolean,
    p_roll_it_back boolean,
    INOUT p_t_id   bigint DEFAULT NULL
) LANGUAGE plpgsql AS $$
DECLARE
    v_c_id      bigint;
    v_b_id      bigint;
    v_exec_name varchar(49);
    v_lt_price  numeric(8,2);
    v_is_mrkt   boolean;
    v_st_id     char(4);
    v_chrg      numeric(10,2) := 10.00;
    v_comm      numeric(10,2) := 15.00;
BEGIN
    SELECT ca_c_id, ca_b_id
      INTO v_c_id, v_b_id
      FROM customer_account
     WHERE ca_id = p_ca_id;

    SELECT c_f_name || ' ' || c_l_name
      INTO v_exec_name
      FROM customer
     WHERE c_id = v_c_id;

    SELECT lt_price
      INTO v_lt_price
      FROM last_trade
     WHERE lt_s_symb = p_s_symb::char(15);

    v_lt_price := COALESCE(v_lt_price, 25.00);

    SELECT tt_is_mrkt
      INTO v_is_mrkt
      FROM trade_type
     WHERE tt_id = p_tt_id::char(3);

    v_st_id := CASE WHEN COALESCE(v_is_mrkt, true) THEN 'SBMT' ELSE 'PNDG' END;

    INSERT INTO trade (
        t_dts, t_st_id, t_tt_id, t_is_cash, t_s_symb, t_qty,
        t_bid_price, t_ca_id, t_exec_name, t_trade_price,
        t_chrg, t_comm, t_tax, t_lifo
    ) VALUES (
        CURRENT_TIMESTAMP, v_st_id, p_tt_id::char(3), true, p_s_symb::char(15), p_qty,
        v_lt_price, p_ca_id, COALESCE(v_exec_name, 'EXEC'), NULL,
        v_chrg, v_comm, 0.00, p_is_lifo
    ) RETURNING t_id INTO p_t_id;

    INSERT INTO trade_history (th_t_id, th_dts, th_st_id)
    VALUES (p_t_id, CURRENT_TIMESTAMP, v_st_id);

    IF NOT COALESCE(v_is_mrkt, true) THEN
        INSERT INTO trade_request (tr_t_id, tr_tt_id, tr_s_symb, tr_qty, tr_bid_price, tr_b_id)
        VALUES (p_t_id, p_tt_id::char(3), p_s_symb::char(15), p_qty, v_lt_price, COALESCE(v_b_id, 1));
    END IF;

    IF p_roll_it_back THEN
        RAISE EXCEPTION 'Intentional Trade-Order Rollback for trade %', p_t_id
            USING ERRCODE = 'P0002';
    END IF;
END;
$$;

--
-- TPC-E: Trade-Result Transaction
--
CREATE OR REPLACE PROCEDURE pgbench_e_trade_result(
    p_t_id        bigint,
    p_trade_price numeric
) LANGUAGE plpgsql AS $$
DECLARE
    v_t_id    bigint;
    v_ca_id   bigint;
    v_s_symb  char(15);
    v_qty     integer;
    v_comm    numeric(10,2);
    v_chrg    numeric(10,2);
    v_is_sell boolean;
    v_b_id    bigint;
    v_se_amt  numeric(10,2);
BEGIN
    SELECT t_id, t_ca_id, t_s_symb, t_qty, t_comm, t_chrg
      INTO v_t_id, v_ca_id, v_s_symb, v_qty, v_comm, v_chrg
      FROM trade
     WHERE t_id = p_t_id
       FOR UPDATE;

    IF NOT FOUND THEN
        SELECT t_id, t_ca_id, t_s_symb, t_qty, t_comm, t_chrg
          INTO v_t_id, v_ca_id, v_s_symb, v_qty, v_comm, v_chrg
          FROM trade
         WHERE t_st_id IN ('SBMT', 'PNDG')
         ORDER BY t_id DESC
         LIMIT 1
           FOR UPDATE SKIP LOCKED;
    END IF;

    IF v_t_id IS NULL THEN
        RETURN;
    END IF;

    SELECT tt_is_sell INTO v_is_sell
      FROM trade_type
      JOIN trade ON t_tt_id = tt_id
     WHERE t_id = v_t_id;

    UPDATE trade
       SET t_st_id = 'CMPT',
           t_trade_price = p_trade_price,
           t_dts = CURRENT_TIMESTAMP
     WHERE t_id = v_t_id;

    INSERT INTO trade_history (th_t_id, th_dts, th_st_id)
    VALUES (v_t_id, CURRENT_TIMESTAMP, 'CMPT')
    ON CONFLICT (th_t_id, th_st_id) DO UPDATE SET th_dts = EXCLUDED.th_dts;

    DELETE FROM trade_request WHERE tr_t_id = v_t_id;

    INSERT INTO holding_summary (hs_ca_id, hs_s_symb, hs_qty)
    VALUES (v_ca_id, v_s_symb, CASE WHEN v_is_sell THEN -v_qty ELSE v_qty END)
    ON CONFLICT (hs_ca_id, hs_s_symb) DO UPDATE
       SET hs_qty = holding_summary.hs_qty + EXCLUDED.hs_qty;

    INSERT INTO holding (h_t_id, h_ca_id, h_s_symb, h_dts, h_price, h_qty)
    VALUES (v_t_id, v_ca_id, v_s_symb, CURRENT_TIMESTAMP, p_trade_price,
            CASE WHEN v_is_sell THEN -v_qty ELSE v_qty END)
    ON CONFLICT (h_t_id) DO NOTHING;

    SELECT ca_b_id INTO v_b_id
      FROM customer_account
     WHERE ca_id = v_ca_id;

    UPDATE broker
       SET b_num_trades = b_num_trades + 1,
           b_comm_total = b_comm_total + v_comm
     WHERE b_id = v_b_id;

    v_se_amt := round(v_qty * p_trade_price - v_chrg - v_comm, 2);

    UPDATE customer_account
       SET ca_bal = ca_bal + CASE WHEN v_is_sell THEN v_se_amt ELSE -v_se_amt END
     WHERE ca_id = v_ca_id;

    INSERT INTO settlement (se_t_id, se_cash_type, se_cash_due_date, se_amt)
    VALUES (v_t_id, 'Cash Account', CURRENT_DATE + 2, v_se_amt)
    ON CONFLICT (se_t_id) DO NOTHING;

    INSERT INTO cash_transaction (ct_t_id, ct_dts, ct_amt, ct_name)
    VALUES (v_t_id, CURRENT_TIMESTAMP, v_se_amt, 'Settlement for ' || trim(v_s_symb))
    ON CONFLICT (ct_t_id) DO NOTHING;
END;
$$;

--
-- TPC-E: Trade-Lookup Transaction
--
CREATE OR REPLACE PROCEDURE tpce_trade_lookup(
    p_ca_id      bigint,
    p_max_trades integer
) LANGUAGE plpgsql AS $$
DECLARE
    v_cnt integer;
BEGIN
    SELECT count(*)
      INTO v_cnt
      FROM (
          SELECT t_id, t_dts, t_st_id, t_trade_price
            FROM trade
           WHERE t_ca_id = p_ca_id
           ORDER BY t_dts DESC
           LIMIT p_max_trades
      ) sub;
END;
$$;

--
-- TPC-E: Trade-Update Transaction
--
CREATE OR REPLACE PROCEDURE tpce_trade_update(
    p_ca_id       bigint,
    p_max_updates integer
) LANGUAGE plpgsql AS $$
BEGIN
    UPDATE trade
       SET t_exec_name = left(trim(t_exec_name) || '-U', 49)
     WHERE t_id IN (
         SELECT t_id
           FROM trade
          WHERE t_ca_id = p_ca_id
          ORDER BY t_dts DESC
          LIMIT p_max_updates
     );
END;
$$;

--
-- TPC-E: Trade-Status Transaction
--
CREATE OR REPLACE PROCEDURE pgbench_e_trade_status(
    p_ca_id bigint
) LANGUAGE plpgsql AS $$
DECLARE
    v_cnt integer;
BEGIN
    SELECT count(*)
      INTO v_cnt
      FROM (
          SELECT t.t_id, t.t_dts, t.t_st_id, t.t_s_symb, t.t_qty, s.s_name
            FROM trade t
            JOIN security s ON s.s_symb = t.t_s_symb
           WHERE t.t_ca_id = p_ca_id
           ORDER BY t.t_dts DESC
           LIMIT 50
      ) sub;
END;
$$;

--
-- TPC-E: Customer-Position Transaction
--
CREATE OR REPLACE PROCEDURE pgbench_e_customer_position(
    p_c_id        bigint,
    p_ca_id       bigint,
    p_get_history boolean
) LANGUAGE plpgsql AS $$
DECLARE
    v_assets numeric(14,2);
    v_hist   integer;
BEGIN
    SELECT COALESCE(sum(hs.hs_qty * lt.lt_price), 0)
      INTO v_assets
      FROM holding_summary hs
      JOIN last_trade lt ON lt.lt_s_symb = hs.hs_s_symb
     WHERE hs.hs_ca_id = p_ca_id;

    IF p_get_history THEN
        SELECT count(*)
          INTO v_hist
          FROM trade t
          JOIN trade_history th ON th.th_t_id = t.t_id
         WHERE t.t_ca_id = p_ca_id;
    END IF;
END;
$$;

--
-- TPC-E: Broker-Volume Transaction
--
CREATE OR REPLACE PROCEDURE pgbench_e_broker_volume(
    p_b_id_min bigint,
    p_b_id_max bigint
) LANGUAGE plpgsql AS $$
DECLARE
    v_total_vol numeric(14,2);
BEGIN
    SELECT COALESCE(sum(tr.tr_qty * tr.tr_bid_price), 0)
      INTO v_total_vol
      FROM broker b
      LEFT JOIN trade_request tr ON tr.tr_b_id = b.b_id
     WHERE b.b_id BETWEEN p_b_id_min AND p_b_id_max;
END;
$$;

--
-- TPC-E: Market-Watch Transaction
--
CREATE OR REPLACE PROCEDURE pgbench_e_market_watch(
    p_wl_id      bigint,
    p_co_id_min  bigint,
    p_co_id_max  bigint,
    INOUT p_pct_change numeric DEFAULT 0
) LANGUAGE plpgsql AS $$
BEGIN
    SELECT COALESCE(
               round((sum(lt.lt_price * s.s_num_out) - sum(lt.lt_open_price * s.s_num_out)) * 100.0 /
                     NULLIF(sum(lt.lt_open_price * s.s_num_out), 0), 4),
               0.0
           )
      INTO p_pct_change
      FROM watch_item wi
      JOIN security s ON s.s_symb = wi.wi_s_symb
      JOIN last_trade lt ON lt.lt_s_symb = s.s_symb
     WHERE wi.wi_wl_id = p_wl_id
        OR s.s_co_id BETWEEN p_co_id_min AND p_co_id_max;
END;
$$;

--
-- TPC-E: Security-Detail Transaction
--
CREATE OR REPLACE PROCEDURE tpce_security_detail(
    p_s_symb text
) LANGUAGE plpgsql AS $$
DECLARE
    v_co_name varchar(60);
    v_price   numeric(8,2);
BEGIN
    SELECT c.co_name, lt.lt_price
      INTO v_co_name, v_price
      FROM security s
      JOIN company c ON c.co_id = s.s_co_id
      JOIN last_trade lt ON lt.lt_s_symb = s.s_symb
     WHERE s.s_symb = p_s_symb::char(15);
END;
$$;

--
-- TPC-E: Market-Feed Transaction
--
CREATE OR REPLACE PROCEDURE tpce_market_feed(
    p_s_symb text,
    p_price  numeric,
    p_qty    integer
) LANGUAGE plpgsql AS $$
BEGIN
    UPDATE last_trade
       SET lt_price = p_price,
           lt_vol = lt_vol + p_qty,
           lt_dts = CURRENT_TIMESTAMP
     WHERE lt_s_symb = p_s_symb::char(15);
END;
$$;
